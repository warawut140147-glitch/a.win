// Workshop 1 · ข้อที่ 4 — ตัดเกรดจากคะแนน
// เกณฑ์: 80-100=A, 75-79=B+, 70-74=B, 65-69=C+, 60-64=C, 55-59=D+, 50-54=D, 0-49=F

// เขียนเป็นฟังก์ชันเพื่อให้เรียกซ้ำได้ ไม่ต้อง copy โค้ดตัดเกรด 13 รอบ
// คืนค่าเป็น string: เกรด หรือ ข้อความแจ้งว่าคะแนนไม่ถูกต้อง
function toGrade(score) {
  // ส่วนที่ 2 — ตรวจข้อมูลนำเข้าก่อนเสมอ (Backend ต้อง validate input)
  // ถ้าไม่เช็คก่อน คะแนน 120 จะได้ A และ -5 จะได้ F ซึ่งผิดทั้งคู่
  if (score < 0 || score > 100) {
    return "คะแนนไม่ถูกต้อง ต้องอยู่ระหว่าง 0-100";
  }

  // ส่วนที่ 1 — ตัดเกรดด้วย if / else if
  // ต้องเรียงจากคะแนนมากไปน้อย เพราะ if/else if จะทำงานเงื่อนไขแรกที่เป็นจริงแล้วออกทันที
  // ถ้าเรียงจากน้อยไปมาก เช่น เช็ค score >= 50 ก่อน คะแนน 80 จะเข้าเงื่อนไข >= 50 ตั้งแต่แรก
  // แล้วได้ D ทั้งที่ควรได้ A — การเรียงมากไปน้อยจึงการันตีว่าแต่ละคะแนนตกช่วงที่แคบที่สุดก่อนเสมอ
  if (score >= 80) {
    return "A";
  } else if (score >= 75) {
    return "B+";
  } else if (score >= 70) {
    return "B";
  } else if (score >= 65) {
    return "C+";
  } else if (score >= 60) {
    return "C";
  } else if (score >= 55) {
    return "D+";
  } else if (score >= 50) {
    return "D";
  } else {
    return "F";
  }
}

// ส่วนที่ 1 — ตัวอย่างผลลัพธ์: คะแนน 78 → เกรด B+
console.log("คะแนน 78 → เกรด " + toGrade(78));

// ส่วนที่ 3 — ทดสอบครบทุกค่า รวมขอบเขตและค่าที่ไม่ถูกต้อง
// for...of วนอ่านค่าใน array ทีละตัว สั้นกว่าเขียน console.log ซ้ำ 13 รอบ
const testScores = [95, 80, 79, 75, 70, 65, 60, 55, 50, 49, 0, -5, 120];

for (const score of testScores) {
  console.log("คะแนน " + score + " → " + toGrade(score));
}
