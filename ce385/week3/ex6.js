// Workshop 1 · ข้อที่ 6 — ระบบตรวจสอบสิทธิ์ (รวมทุกหัวข้อ)
// ข้อมูลที่ถูกต้อง: username = "admin" · password = "ce385pass" · role = "อาจารย์" หรือ "นักศึกษา"

// ส่วนที่ 1 — ฟังก์ชัน login คืนค่าเป็นข้อความผลลัพธ์ (return ไม่ใช่ console.log ข้างใน)
// ใช้ early return ตรวจจากผิดไปถูกตามลำดับที่โจทย์กำหนด — ลำดับสำคัญมาก ดูคำอธิบายท้ายไฟล์
function login(inputUser, inputPass, role, isActive, age) {
  // 1) ตรวจตัวตนก่อนเสมอ (เทียบกับ HTTP 401: ยังพิสูจน์ตัวตนไม่ผ่าน)
  if (inputUser !== "admin" || inputPass !== "ce385pass") {
    return "ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง";
  }

  // 2) ผ่านตัวตนแล้ว ค่อยเปิดเผยสถานะบัญชี (เทียบกับ HTTP 403: รู้ตัวตนแล้วแต่ถูกห้าม)
  if (isActive === false) {
    return "บัญชีนี้ถูกระงับการใช้งาน";
  }

  // 3) ค่อยตรวจเกณฑ์อายุ
  if (age < 18) {
    return "อายุไม่ถึงเกณฑ์";
  }

  // 4-5) ผ่านทุกด่าน ค่อยแยกสิทธิ์ตาม role
  if (role === "อาจารย์") {
    return "เข้าสู่ระบบสำเร็จ (สิทธิ์ผู้ดูแล)";
  }

  return "เข้าสู่ระบบสำเร็จ (สิทธิ์ทั่วไป)";
}

// ส่วนที่ 2 — ทดสอบครบ 6 กรณี (เก็บเป็น array แล้ว for...of จะได้ไม่ต้องเรียกซ้ำ)
const testCases = [
  { name: "สำเร็จ (อาจารย์)",        args: ["admin", "ce385pass", "อาจารย์", true, 30] },
  { name: "สำเร็จ (นักศึกษา)",       args: ["admin", "ce385pass", "นักศึกษา", true, 20] },
  { name: "รหัสผ่านผิด",             args: ["admin", "wrongpass", "อาจารย์", true, 30] },
  { name: "ชื่อผู้ใช้ผิด",           args: ["hacker", "ce385pass", "นักศึกษา", true, 20] },
  { name: "บัญชีถูกระงับ",           args: ["admin", "ce385pass", "นักศึกษา", false, 20] },
  { name: "อายุไม่ถึง 18",           args: ["admin", "ce385pass", "นักศึกษา", true, 15] }
];

for (const testCase of testCases) {
  // กระจาย args ด้วย spread (...) = login(args[0], args[1], ...)
  const result = login(...testCase.args);
  console.log(testCase.name + " → " + result);
}

